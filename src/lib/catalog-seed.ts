/** Identifies starter/demo catalog items so the admin can bulk-clean or restore them anytime. */
export function isSeededCatalogProduct(productOrId: string | Pick<Product, 'id'>): boolean {
  const id = typeof productOrId === 'string' ? productOrId : productOrId.id;
  return typeof id === 'string' && id.startsWith(SEED_CATALOG_ID_PREFIX);
}
